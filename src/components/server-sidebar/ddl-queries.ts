export function newEventTriggerTemplate(): string {
  return `-- Event triggers fire on DDL anywhere in the database, and belong to
-- the database rather than to a schema.
CREATE OR REPLACE FUNCTION public.new_event_trigger_function()
RETURNS event_trigger
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE NOTICE 'ddl: %', tg_tag;
END;
$$;

CREATE EVENT TRIGGER new_event_trigger
  ON ddl_command_end
  EXECUTE FUNCTION public.new_event_trigger_function();`;
}

